const byCode = new Map(SYNC_ENTITY_DEFINITIONS.map((definition) => [definition.code, definition]));

export function getSyncEntity(code: string): SyncEntityDefinition {
  const definition = byCode.get(code);
  if (!definition) throw new Error(`Unknown sync entity type: ${code}`);
  return definition;
}

export function tryGetSyncEntity(code: string): SyncEntityDefinition | undefined {
  return byCode.get(code);
}

export function syncEntityByTable(table: string): SyncEntityDefinition | undefined {
  return SYNC_ENTITY_DEFINITIONS.find((definition) => definition.table === table);
}
