/**
 * Single source of truth for:
 *  - which tables are syncable,
 *  - which fields may be changed through the generic repository,
 *  - which fields are too sensitive for the local audit log,
 *  - how dependent rows behave on soft deletion,
 *  - the conflict policy category stored in `sync_entity_type`.
 *
 * `sync_entity_type` is seeded from this list by migration 1. The same list
 * drives BaseRepository guards, so the documentation and the code cannot drift
 * silently.
 */

export type SyncPolicy = 'field_merge' | 'relation_set' | 'append_only' | 'immutable' | 'ledger';

export type DependentPolicy = 'block' | 'cascade';

export interface DependentRule {
  readonly table: string;
  readonly column: string;
  readonly policy: DependentPolicy;
  /** Arabic label used in the conflict error shown to the user later. */
  readonly labelAr: string;
}

export interface SyncEntityDefinition {
  readonly code: string;
  readonly table: string;
  readonly descriptionAr: string;
  readonly policy: SyncPolicy;
  readonly primaryKeyColumn: string;
  readonly mutableColumns: readonly string[];
  readonly sensitiveColumns: readonly string[];
  readonly softDelete: boolean;
  readonly archiveColumn?: string;
  readonly dependents: readonly DependentRule[];
}

const dependent = (
  table: string,
  column: string,
  policy: DependentPolicy,
  labelAr: string,
): DependentRule => ({ table, column, policy, labelAr });

