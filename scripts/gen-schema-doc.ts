/**
 * Generates docs/schema-v2.md from the actual migrated schema so the data
 * dictionary cannot drift from the DDL.
 */
import { writeFileSync } from 'node:fs';
import { PORTABLE_SCHEMA } from '../src/schema/current.ts';
import { LawOfficeDatabase } from '../src/app/law-office-database.ts';

const { database: db } = LawOfficeDatabase.open({
  path: ':memory:',
  appVersion: '0.3.0-doc',
});
const sqlRows = db.db.query<{ name: string; sql: string | null }>(
  "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE 'search_fts_%' ORDER BY name",
);

const lines: string[] = [];
const output = `docs/schema-v${PORTABLE_SCHEMA.schemaVersion}.md`;
lines.push(`# Data dictionary (schema v${PORTABLE_SCHEMA.schemaVersion})`);
lines.push('');
lines.push(
  `The portable application schema has ${PORTABLE_SCHEMA.tables.length} tables. This SQLite dictionary also includes the FTS5 virtual table; FTS shadow tables are omitted. The virtual table is not a second business store and is not required by IndexedDB.`,
);
lines.push('');
lines.push(
  'Generated by `scripts/gen-schema-doc.ts` from a freshly migrated database. Types are SQLite storage classes; `STRICT` tables reject values outside those classes. `TEXT` timestamps are canonical UTC ISO-8601 strings (`YYYY-MM-DDTHH:MM:SS.sssZ`); legal dates are `YYYY-MM-DD`. Money is an integer number of piastres (EGP minor units).',
);
lines.push('');
lines.push(
  'Every syncable table carries: `created_at`, `updated_at`, `deleted_at`, `origin_device_id`, `revision`, `sync_status`, `last_synced_at`. Lookup tables are reference data; names are seeded in Arabic and English but are editable rows, never enums in code.',
);
lines.push('');

for (const table of sqlRows) {
  if (table.name === 'search_fts') continue;
  lines.push(`## ${table.name}`);
  lines.push('');
  const columns = db.db.query<{
    cid: number;
    name: string;
    type: string;
    notnull: number;
    dflt_value: string | null;
    pk: number;
  }>(`PRAGMA table_info("${table.name}")`);
  lines.push('| Column | Storage type | Null | Default | PK |');
  lines.push('| --- | --- | --- | --- | --- |');
  for (const column of columns) {
    lines.push(
      `| \`${column.name}\` | ${column.type || '(any)'} | ${column.notnull ? 'NO' : 'yes'} | ${
        column.dflt_value === null ? '—' : `\`${column.dflt_value}\``
      } | ${column.pk ? column.pk : ''} |`,
    );
  }
  const foreignKeys = db.db.query<{
    table: string;
    from: string;
    to: string;
    on_delete: string;
  }>(`PRAGMA foreign_key_list("${table.name}")`);
  if (foreignKeys.length > 0) {
    lines.push('');
    lines.push('Foreign keys:');
    for (const foreignKey of foreignKeys) {
      lines.push(
        `- \`${foreignKey.from}\` → \`${foreignKey.table}\`(\`${foreignKey.to}\`) on delete ${foreignKey.on_delete}`,
      );
    }
  }
  const indexes = db.db.query<{ name: string; unique: number; origin: string }>(
    `PRAGMA index_list("${table.name}")`,
  );
  const named = indexes.filter(
    (index) => !index.name.startsWith('sqlite_autoindex'),
  );
  const auto = indexes.filter((index) =>
    index.name.startsWith('sqlite_autoindex'),
  );
  if (named.length > 0) {
    lines.push('');
    lines.push('Indexes:');
    for (const index of named) {
      const cols = db.db
        .query<{ name: string }>(`PRAGMA index_info("${index.name}")`)
        .map((row) => row.name)
        .join(', ');
      lines.push(
        `- \`${index.name}\` (${index.unique ? 'unique' : 'non-unique'}): ${cols}`,
      );
    }
  }
  if (auto.length > 0) {
    lines.push('');
    lines.push(
      `Implicit UNIQUE/PK indexes: ${auto.map((index) => `\`${index.name}\``).join(', ')}`,
    );
  }
  if (table.sql) {
    const constraints = table.sql
      .split('\n')
      .map((line) => line.trim())
      .filter((line) => /^(CHECK|UNIQUE|FOREIGN KEY|CONSTRAINT)/.test(line));
    if (constraints.length > 0) {
      lines.push('');
      lines.push('Table constraints:');
      for (const constraint of constraints)
        lines.push(`- \`${constraint.replace(/,$/, '')}\``);
    }
  }
  lines.push('');
}

lines.push('## Reference data (seed)');
lines.push('');
for (const list of db.lookups.allLists()) {
  const items = db.lookups.itemsOf(list.code, { includeInactive: true });
  lines.push(`### ${list.code} — ${list.name_ar}`);
  lines.push('');
  lines.push(
    items.map((item) => `\`${item.code}\` (${item.name_ar})`).join(' · '),
  );
  lines.push('');
}

lines.push(
  `_Generated ${new Date().toISOString()}; ${sqlRows.length} tables._`,
);
writeFileSync(output, `${lines.join('\n')}\n`);
process.stdout.write(
  `${output} written: ${sqlRows.length} SQLite table entries\n`,
);
db.close();
